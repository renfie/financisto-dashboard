def drain_one(db_path,secret,subject):
    from tempfile import NamedTemporaryFile
    from pywebpush import webpush,WebPushException
    now=int(time.time())
    with sqlite3.connect(db_path,timeout=15) as db:
        db.row_factory=sqlite3.Row
        db.execute('BEGIN IMMEDIATE')
        db.execute("UPDATE webpush_outbox SET status='pending' WHERE status='sending' AND claimed_epoch<?",(now-180,))
        row=db.execute("""SELECT o.*, s.endpoint,s.p256dh,s.auth,s.user_id,
                   u.is_active FROM webpush_outbox o
                   LEFT JOIN webpush_subscriptions s ON s.id=o.subscription_id
                   LEFT JOIN users u ON u.id=s.user_id
                   WHERE o.status='pending' AND o.next_attempt_epoch<=?
                   ORDER BY o.id LIMIT 1""",(now,)).fetchone()
        if not row: return False
        db.execute("UPDATE webpush_outbox SET status='sending',attempts=attempts+1,claimed_epoch=? WHERE id=?",
                   (now,row['id']))
        config=db.execute('SELECT private_key_enc FROM webpush_config WHERE id=1').fetchone()
    if not row['endpoint'] or not row['is_active'] or not config:
        with sqlite3.connect(db_path) as db:
            db.execute("UPDATE webpush_outbox SET status='failed',last_error='Empfänger nicht aktiv' WHERE id=?",(row['id'],))
        return True
    # Treat database-backed endpoint as untrusted even after storage.
    try:
        _valid_endpoint(row['endpoint'])
        private=decrypt(config['private_key_enc'],secret)
        with sqlite3.connect(db_path,timeout=15) as connection:
            connection.row_factory=sqlite3.Row
            payload=_payload(connection,row,row['user_id'])
        payload.update({'url':'/','tag':f"fielanzen-{row['event']}-{row['ref']}"})
        # pywebpush accepts a private PEM file; temp file exists only in RAM-backed /tmp.
        with NamedTemporaryFile(mode='w',suffix='.pem',delete=True) as pem:
            pem.write(private); pem.flush()
            webpush(subscription_info={'endpoint':row['endpoint'],
               'keys':{'p256dh':row['p256dh'],'auth':row['auth']}},
               data=json.dumps(payload,ensure_ascii=False),
               vapid_private_key=pem.name,vapid_claims={'sub':subject},ttl=3600,timeout=8)
    except Exception as exc:
        expired=(getattr(getattr(exc,'response',None),'status_code',None) in (404,410))
        retry=max(60,min(1800,60*2**min(int(row['attempts']),5)))
        with sqlite3.connect(db_path,timeout=15) as db:
            if expired:
                delete_subscription(db,row['subscription_id'])
            else:
                db.execute("""UPDATE webpush_outbox SET status=?,last_error=?,next_attempt_epoch=?
                    WHERE id=?""",('failed' if row['attempts']>=4 else 'pending',
                           type(exc).__name__[:55],now+retry,row['id']))
        # Never log subscription endpoint or any secret.
        LOG.warning('Push ID %s fehlgeschlagen: %s',row['id'],type(exc).__name__)
    else:
        with sqlite3.connect(db_path) as db:
            db.execute("UPDATE webpush_outbox SET status='sent',sent_at=CURRENT_TIMESTAMP WHERE id=?",(row['id'],))
            db.execute('UPDATE webpush_subscriptions SET last_sent_at=CURRENT_TIMESTAMP WHERE id=?',
                       (row['subscription_id'],))
    return True

  const ignore = 'script, style, code, pre, textarea, [contenteditable], [data-no-i18n], .account-balance-name, .bar-title, .transaction-payee, .transaction-note, .booking-text';
  function forbidden(node) {
    const parent = node.nodeType === 1 ? node : node.parentElement;
    return !parent || !!parent.closest(ignore);
  }
  function translateText(node) {
    if (!node || node.nodeType !== 3 || forbidden(node)) return;
    const original = node.nodeValue;
    const cleaned = original.trim();
    const result = translate(cleaned);
    if (result === cleaned || result === original) return;
    node.nodeValue = original.replace(cleaned,result);
  }
  const translatedAttrs = ['placeholder','aria-label','title','data-confirm','aria-description'];
  function translateAttrs(el) {
    if (el.nodeType !== 1 || forbidden(el)) return;
    for (const attr of translatedAttrs) {
      if (!el.hasAttribute(attr)) continue;
      const original = el.getAttribute(attr);
      const result = translate(original);
      if (result !== original) el.setAttribute(attr,result);
    }
  }
  function translateTree(root) {
    if (language !== 'en' || !root) return;
    if (root.nodeType === 3) {translateText(root);return;}
    if (root.nodeType !== 1 && root.nodeType !== 9) return;
    if (root.nodeType === 1) translateAttrs(root);
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
    let element;
    while ((element=walker.nextNode())) {
      if (element.nodeType === 3) translateText(element);
      else translateAttrs(element);
    }
  }
  if (language === 'en') {
    translateTree(document.body);
    document.title = document.title.split(' · ').map(part => translate(part)).join(' · ');
    // Translates UI text injected after load (e.g. dialogs, sortable tables,
    // the onboarding tour and validation messages). No network or persistence.
    const observer = new MutationObserver((mutations) => {
      for (const entry of mutations) {
        if (entry.type === 'characterData') translateText(entry.target);
        else if (entry.type === 'attributes') translateAttrs(entry.target);
        else for (const added of entry.addedNodes) translateTree(added);
      }
    });
    observer.observe(document.body,{childList:true,subtree:true,characterData:true,attributes:true,attributeFilter:translatedAttrs});
  }
  if (language === 'en') {
    const originalConfirm = window.confirm.bind(window);
    const originalAlert = window.alert.bind(window);
    window.confirm = message => originalConfirm(translate(String(message)));
    window.alert = message => originalAlert(translate(String(message)));
  }
  window.FinancistoI18n = Object.freeze({language,translate});
